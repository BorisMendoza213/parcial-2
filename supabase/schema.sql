-- Esquema de base de datos para Supabase (Mi Tienda)
-- Tabla de productos para sincronización con la app móvil

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  client_id text not null unique,
  name text not null,
  quantity integer not null,
  price integer not null,
  updated_at timestamptz not null default now()
);

-- Habilitar Row Level Security (RLS)
alter table public.products enable row level security;

-- Política: los usuarios solo pueden ver y gestionar sus propios productos
create policy "Los usuarios gestionan sus propios productos"
on public.products for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);
